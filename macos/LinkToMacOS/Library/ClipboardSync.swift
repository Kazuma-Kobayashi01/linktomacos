import AppKit
import LinkCore
import os

private let log = Logger(subsystem: "com.linktomacos.mac", category: "clipboard")

/// 和手机互通剪贴板文本。
///
/// 系统不通知剪贴板变化，只能每隔一会儿看一次 `changeCount`；只在有手机连着的时候才轮询。
/// 刚连上时不把已有的剪贴板内容发出去，只同步之后的复制。密码管理器等标成“隐藏”或“临时”的内容不往外发。
@MainActor
final class ClipboardSync {
    /// 剪贴板里带这些类型的内容是密码管理器等标出来的敏感或临时内容（nspasteboard.org 约定）。
    private static let privateTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    private let pasteboard = NSPasteboard.general
    private var timer: Timer?
    private var seenChangeCount = 0
    /// 最近一次收发的文本：挡住刚从手机收到的内容又被当成“Mac 上新复制的”发回去。
    private var last: String?

    /// 要发给手机的文本，由 AppModel 指定发给哪台手机。
    var send: ((ClipboardText) -> Void)?

    /// 有没有手机连着。
    var isActive = false {
        didSet {
            guard isActive != oldValue else { return }
            if isActive {
                seenChangeCount = pasteboard.changeCount
                timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
                    MainActor.assumeIsolated { self?.poll() }
                }
            } else {
                timer?.invalidate()
                timer = nil
            }
        }
    }

    private var enabled: Bool { Prefs.bool(Prefs.syncClipboard, default: true) }

    private func poll() {
        guard pasteboard.changeCount != seenChangeCount else { return }
        seenChangeCount = pasteboard.changeCount
        guard enabled else { return }
        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.privateTypes),
              let text = pasteboard.string(forType: .string),
              !text.isEmpty, text.count <= ClipboardText.maxCharacters, text != last
        else { return }
        last = text
        send?(ClipboardText(text: text, timestamp: Int64(Date().timeIntervalSince1970 * 1000)))
    }

    /// 手机上复制了文本。
    func receive(_ clip: ClipboardText) {
        guard enabled, !clip.text.isEmpty, clip.text.count <= ClipboardText.maxCharacters, clip.text != last else { return }
        last = clip.text
        pasteboard.clearContents()
        pasteboard.setString(clip.text, forType: .string)
        seenChangeCount = pasteboard.changeCount  // 这次写入不算 Mac 上的复制
        log.debug("received clipboard text (\(clip.text.count) characters)")
    }
}
